#!/usr/bin/env node
// Dumps BACKPACK_ITEMS as a markdown table for docs/backpack-catalog.md.
//
//   node tools/dump-bp-catalog.js > docs/backpack-catalog.md
//
// Reads src/config/config.js, evaluates it in a sandbox the same way
// the test suite does, and emits a sorted-by-rarity-then-name table
// with the rarity pill, tag icons, shape outline, and effect summary
// for every item.

'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const cfgSrc = fs.readFileSync(path.join(__dirname, '..', 'src/config/config.js'), 'utf8')
    .replace(/^const /gm, 'var ')
    .replace(/^let /gm,   'var ');
const sandbox = { window: {}, document: {} };
vm.createContext(sandbox);
vm.runInContext(cfgSrc, sandbox);
const ITEMS = sandbox.BACKPACK_ITEMS;

const RARITY_ORDER = ['common', 'uncommon', 'rare', 'epic', 'legendary'];
const RARITY_LETTER = { common: 'C', uncommon: 'U', rare: 'R', epic: 'E', legendary: 'L' };
const TAG_GLYPH = { power: '⚡', tech: '⚙', econ: '¢', core: '♥' };

function shapeAscii(shape) {
    if (!shape) return '';
    return shape.map(row => row.map(c => c ? '█' : ' ').join('')).join(' / ');
}
function effectSummary(eff, synergy) {
    if (!eff) return '—';
    const parts = [];
    if (eff.damage)      parts.push(`+${Math.round(eff.damage * 100)}% damage`);
    if (eff.fireRate)    parts.push(`+${Math.round(eff.fireRate * 100)}% fire rate`);
    if (eff.payout)      parts.push(`+${Math.round(eff.payout * 100)}% payout`);
    if (eff.kill)        parts.push(`+${Math.round(eff.kill * 100)}% per-kill`);
    if (eff.maxHP)       parts.push(`+${eff.maxHP} max HP`);
    if (eff.interest)    parts.push(`+${Math.round(eff.interest * 100)}% interest`);
    if (eff.towerCost)   parts.push(`−${Math.round(eff.towerCost * 100)}% tower cost`);
    if (eff.upgradeCost) parts.push(`−${Math.round(eff.upgradeCost * 100)}% upgrade cost`);
    if (eff.startMoney)  parts.push(`+${eff.startMoney}¢ start`);
    if (eff.regen)       parts.push(`+${eff.regen} regen/wave`);
    let s = parts.join(' · ');
    if (synergy) {
        s += ` ✦ adj ${synergy.tags.join('|')}: ${effectSummary(synergy.perAdj)} (cap ${synergy.max})`;
    }
    return s || '—';
}

const grouped = {};
for (const r of RARITY_ORDER) grouped[r] = [];
for (const id of Object.keys(ITEMS)) {
    const it = ITEMS[id];
    grouped[it.rarity].push(it);
}

console.log('# Backpack Catalog');
console.log('');
console.log('_Auto-generated by `node tools/dump-bp-catalog.js`._');
console.log('');
console.log('Rarity letters on the placed grid: **C** Common · **U** Uncommon · **R** Rare · **E** Epic · **L** Legendary.');
console.log('');
console.log('Tag glyphs (placed anchor + stash pills):');
console.log('');
console.log('| Glyph | Tag | Stat focus |');
console.log('|---|---|---|');
console.log('| ⚡ | power | tower damage, fire rate |');
console.log('| ⚙ | tech  | fire rate, build/upgrade discounts |');
console.log('| ¢ | econ  | payout, kill, interest, starting credits |');
console.log('| ♥ | core  | max integrity, regen |');
console.log('');

for (const rarity of RARITY_ORDER) {
    const items = grouped[rarity];
    if (!items.length) continue;
    console.log(`## ${rarity[0].toUpperCase() + rarity.slice(1)}  (${RARITY_LETTER[rarity]})`);
    console.log('');
    console.log('| Name | Tags | Shape | Effect |');
    console.log('|---|---|---|---|');
    items.sort((a, b) => a.name.localeCompare(b.name));
    for (const it of items) {
        const tags = (it.tags || []).map(t => `${TAG_GLYPH[t] || '·'} ${t}`).join(' ');
        const shape = '`' + shapeAscii(it.shape) + '`';
        const eff = effectSummary(it.effect, it.synergy);
        console.log(`| **${it.name}** | ${tags} | ${shape} | ${eff} |`);
    }
    console.log('');
}

console.log('---');
console.log('');
console.log('All entries are validated by `tests/backpack-catalog.test.js` —');
console.log('every item must have a rarity, ≥ 1 tag, a non-empty 0/1 shape,');
console.log('a non-empty description, and an effect object whose keys are in');
console.log('the known schema (damage, fireRate, payout, kill, maxHP,');
console.log('interest, towerCost, upgradeCost, startMoney, regen).');
